#!/usr/bin/env python3
"""Generate the package HTTP encoder's NFC tables from JDK21 (Unicode 15), offline.

Only this development tool uses a JDK internal API to read combining classes.
The native product has no Java dependency. --check also pins the extracted data.
"""
import argparse
import hashlib
import os
from pathlib import Path
import subprocess
import tempfile

try:
    from java_tmp import java_command
except ModuleNotFoundError:
    from scripts.java_tmp import java_command


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'rust/unlaxer-generator/src/packages/java_uri/nfc_data.rs'
SOURCE = '''import java.text.Normalizer;
import jdk.internal.icu.lang.UCharacter;
class PackageNfcData {
    public static void main(String[] args) {
        for (int c = 0; c <= 0x10ffff; c++) {
            if (c >= 0xd800 && c <= 0xdfff) continue;
            int k = UCharacter.getCombiningClass(c);
            if (k != 0) System.out.printf("C;%X;%d%n", c, k);
            if (c >= 0xac00 && c <= 0xd7a3) continue; // Algorithmic Hangul.
            String s = new String(Character.toChars(c));
            String d = Normalizer.normalize(s, Normalizer.Form.NFD);
            if (s.equals(d)) continue;
            System.out.printf("D;%X;", c);
            d.codePoints().forEach(x -> System.out.printf("%X,", x));
            System.out.println();
            if (!Normalizer.normalize(s, Normalizer.Form.NFC).equals(s)) continue;
            int last = d.offsetByCodePoints(d.length(), -1);
            String first = Normalizer.normalize(d.substring(0, last), Normalizer.Form.NFC);
            if (first.codePointCount(0, first.length()) != 1) throw new AssertionError();
            System.out.printf("P;%X;%X;%X%n", first.codePointAt(0), d.codePointAt(last), c);
        }
    }
}
'''


def generate(java_home):
    export = '--add-exports=java.base/jdk.internal.icu.lang=ALL-UNNAMED'
    with tempfile.TemporaryDirectory(prefix='package-nfc-', dir=os.environ.get('TMPDIR')) as tmp:
        path = Path(tmp)
        (path / 'PackageNfcData.java').write_text(SOURCE, encoding='ascii')
        subprocess.run(java_command(str(java_home / 'bin/javac')) + [export, str(path / 'PackageNfcData.java')], check=True)
        raw = subprocess.check_output(java_command(str(java_home / 'bin/java')) + [export, '-cp', tmp, 'PackageNfcData'])
    checksum = hashlib.sha256(raw).hexdigest()
    # Filled from Oracle JDK21.0.9; rejects a different Unicode version on regeneration.
    expected = '76318146c31b727624049ea3f76cdf6167adabd17e0ac323771d2e9ecabcd9ad'
    if checksum != expected:
        raise SystemExit('package NFC data version differs: ' + checksum)
    classes, decomposed, pairs = [], [], []
    for line in raw.decode('ascii').splitlines():
        fields = line.split(';')
        if fields[0] == 'C':
            cp, k = int(fields[1], 16), int(fields[2])
            if classes and classes[-1][1] + 1 == cp and classes[-1][2] == k:
                classes[-1] = (classes[-1][0], cp, k)
            else:
                classes.append((cp, cp, k))
        elif fields[0] == 'D':
            decomposed.append((int(fields[1], 16), [int(v, 16) for v in fields[2].strip(',').split(',')]))
        else:
            pairs.append(tuple(int(v, 16) for v in fields[1:]))
    text = ('// Generated by scripts/generate-package-nfc.py; JDK21 / Unicode 15.0 NFC.\n'
            '// Unicode data: Copyright Unicode, Inc.; see spec-corpus/case-insensitive/UNICODE-LICENSE.txt.\n'
            '// Extracted data SHA-256: ' + checksum + '\n\n')
    text += '#[rustfmt::skip]\npub(super) const CLASSES: &[(u32, u32, u8)] = &[\n'
    text += ''.join(f'    (0x{a:x}, 0x{b:x}, {k}),\n' for a, b, k in classes) + '];\n\n'
    # Fixed arrays (0-padded; U+0000 never occurs) avoid one pointer and relocation per row.
    width = max(len(d) for _, d in decomposed)
    text += f'#[rustfmt::skip]\npub(super) const DECOMPOSED: &[(u32, [u32; {width}])] = &[\n'
    text += ''.join(f'    (0x{cp:x}, [' + ', '.join(f'0x{c:x}' for c in d + [0] * (width - len(d))) + ']),\n'
                    for cp, d in decomposed) + '];\n\n'
    text += '#[rustfmt::skip]\npub(super) const PAIRS: &[(u32, u32, u32)] = &[\n'
    text += ''.join(f'    (0x{a:x}, 0x{b:x}, 0x{c:x}),\n' for a, b, c in sorted(pairs)) + '];\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--java-home', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.java_home)
    if args.check:
        if OUTPUT.read_text() != content:
            raise SystemExit('package NFC table drift')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding='ascii')


if __name__ == '__main__':
    main()
