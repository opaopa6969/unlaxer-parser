#!/usr/bin/env python3
"""Generate Unicode 17 simple lower(upper(cp)) keys for Java/Rust, offline."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'spec-corpus/case-insensitive/unicode-17.0.0'


def generate():
    raw = (SOURCE / 'UnicodeData.txt').read_bytes()
    digest = (SOURCE / 'SHA256SUMS').read_text(encoding='ascii').split()[0]
    if hashlib.sha256(raw).hexdigest() != digest:
        raise SystemExit('UnicodeData.txt SHA-256 mismatch')
    upper, lower = {}, {}
    for line in raw.decode('utf-8').splitlines():
        fields = line.split(';')
        cp = int(fields[0], 16)
        if fields[12]:
            upper[cp] = int(fields[12], 16)
        if fields[13]:
            lower[cp] = int(fields[13], 16)
    def key(cp):
        capital = upper.get(cp, cp)
        return lower.get(capital, capital)
    rows = [(cp, key(cp)) for cp in sorted(upper.keys() | lower.keys()) if key(cp) != cp]
    for cp in range(0x110000):
        if key(key(cp)) != key(cp):
            raise ValueError('case key is not idempotent')
        if (cp > 0xffff) != (key(cp) > 0xffff):
            raise ValueError('simple case mapping changes UTF-16 width')
    notice = ('// Generated by scripts/generate-case-tables.py; Unicode 17.0.0.\n'
              '// Copyright (c) 2025 Unicode, Inc. See spec-corpus/case-insensitive/UNICODE-LICENSE.txt.\n')
    java = notice + '''package org.unlaxer.parser.elementary;

/** Unicode simple mappings only: no locale, normalization, or multi-scalar folding. */
final class UnicodeCaseData {
    private UnicodeCaseData() {}
    static int key(int cp) {
        int low = 0, high = KEYS.length / 2;
        while (low < high) {
            int middle = (low + high) >>> 1;
            int candidate = KEYS[2 * middle];
            if (cp < candidate) { high = middle; }
            else if (cp > candidate) { low = middle + 1; }
            else { return KEYS[2 * middle + 1]; }
        }
        return cp;
    }
    private static final int[] KEYS = {
'''
    java += ''.join(f'        0x{cp:x}, 0x{value:x},\n' for cp, value in rows)
    java += '    };\n}\n'
    rust = notice + '''pub(crate) fn key(cp: char) -> u32 {
    let cp = cp as u32;
    KEYS.binary_search_by_key(&cp, |&(source, _)| source)
        .map_or(cp, |index| KEYS[index].1)
}

#[rustfmt::skip]
const KEYS: &[(u32, u32)] = &[
'''
    rust += ''.join(f'    (0x{cp:x}, 0x{value:x}),\n' for cp, value in rows)
    rust += '];\n'
    return {
        ROOT / 'unlaxer-common/src/main/java/org/unlaxer/parser/elementary/UnicodeCaseData.java': java,
        ROOT / 'rust/unlaxer-runtime/src/unicode_case_data.rs': rust,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, content in generate().items():
        if options.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Unicode case table drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
