#!/usr/bin/env python3
"""Generate pinned Unicode 17 grapheme property tables for both runtimes, offline."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'spec-corpus/grapheme/unicode-17.0.0'
GCB = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
       'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
INCB = ['None', 'Consonant', 'Extend', 'Linker']


def read(name, properties, prefix=None):
    rows = []
    for line in (SOURCE / name).read_text(encoding='utf-8').splitlines():
        data = line.split('#')[0].strip()
        if not data:
            continue
        fields = [field.strip() for field in data.split(';')]
        if prefix:
            if fields[1] != prefix:
                continue
            fields.pop(1)
        if fields[1] not in properties:
            continue
        limits = fields[0].split('..')
        rows.append((int(limits[0], 16), int(limits[-1], 16), properties.index(fields[1])))
    rows.sort()
    merged = []
    for start, end, value in rows:
        if merged and merged[-1][1] >= start:
            raise ValueError('overlapping property intervals')
        if merged and merged[-1][1] + 1 == start and merged[-1][2] == value:
            merged[-1] = merged[-1][0], end, value
        else:
            merged.append((start, end, value))
    return merged


def generate():
    tables = [
        ('GCB', read('GraphemeBreakProperty.txt', GCB)),
        ('INCB', read('DerivedCoreProperties.txt', INCB, 'InCB')),
        ('PICTOGRAPHIC', read('emoji-data.txt', ['None', 'Extended_Pictographic'])),
    ]
    notice = ('// Generated by scripts/generate-grapheme-tables.py; Unicode 17.0.0.\n'
              '// Copyright (c) 2025 Unicode, Inc. See spec-corpus/grapheme/UNICODE-LICENSE.txt.\n')
    java = notice + '''package org.unlaxer.source;

final class UnicodeGraphemeData {
    private UnicodeGraphemeData() {}
    static int gcb(int cp) { return lookup(GCB, cp); }
    static int incb(int cp) { return lookup(INCB, cp); }
    static boolean pictographic(int cp) { return lookup(PICTOGRAPHIC, cp) != 0; }
    private static int lookup(int[] ranges, int cp) {
        int low = 0, high = ranges.length / 3;
        while (low < high) {
            int middle = (low + high) >>> 1;
            if (cp < ranges[3 * middle]) { high = middle; }
            else if (cp > ranges[3 * middle + 1]) { low = middle + 1; }
            else { return ranges[3 * middle + 2]; }
        }
        return 0;
    }
'''
    rust = notice + '''pub(crate) fn gcb(cp: u32) -> u8 {
    lookup(GCB, cp)
}
pub(crate) fn incb(cp: u32) -> u8 {
    lookup(INCB, cp)
}
pub(crate) fn pictographic(cp: u32) -> bool {
    lookup(PICTOGRAPHIC, cp) != 0
}
fn lookup(ranges: &[(u32, u32, u8)], cp: u32) -> u8 {
    ranges
        .binary_search_by(|&(start, end, _)| {
            if cp < start {
                std::cmp::Ordering::Greater
            } else if cp > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .map_or(0, |index| ranges[index].2)
}
'''
    for prefix, values in [('GCB', GCB), ('INCB', INCB)]:
        for value, name in enumerate(values):
            constant = prefix + '_' + name.upper()
            java += f'    static final int {constant} = {value};\n'
            rust += f'pub(crate) const {constant}: u8 = {value};\n'
    for name, rows in tables:
        java += f'    private static final int[] {name} = {name.lower()}Data();\n'
        java += f'    private static int[] {name.lower()}Data() {{ return new int[] {{\n'
        java += ''.join(f'        0x{a:x}, 0x{b:x}, {value},\n' for a, b, value in rows)
        java += '    }; }\n'
        rust += f'\n#[rustfmt::skip]\nconst {name}: &[(u32, u32, u8)] = &[\n'
        rust += ''.join(f'    (0x{a:x}, 0x{b:x}, {value}),\n' for a, b, value in rows)
        rust += '];\n'
    java += '}\n'
    return {
        ROOT / 'unlaxer-common/src/main/java/org/unlaxer/source/UnicodeGraphemeData.java': java,
        ROOT / 'rust/unlaxer-runtime/src/unicode_grapheme_data.rs': rust,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, content in generate().items():
        if options.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Unicode grapheme table drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
