    /** Reflection access to one generated Java grammar and its independent observation. */
    private static final class JavaApi {
        final Parser root;
        final Class<?> mapper;
        final Set<String> rules = new TreeSet<>();
        final List<String> owned;
        final String caseId;
        /** Step count of every input checked by {@link #withinBudget}, for the evidence. */
        final Map<String, Long> steps = new java.util.HashMap<>();
        /** Message of the last mapping failure; reported, not compared (wording is host-specific). */
        String mapError;

        JavaApi(ClassLoader loader, String pkg, String name, Case source) throws Exception {
            root = (Parser) loader.loadClass(pkg + "." + name + "Parsers").getMethod("getRootParser").invoke(null);
            mapper = loader.loadClass(pkg + "." + name + "Mapper");
            rules.addAll(source.ruleNames());
            owned = source.ownedNames();
            caseId = source.id();
        }

        /** Thrown by the step counter; carries no stack trace (#739). */
        private static final class StepBudgetExceeded extends RuntimeException {
            private static final long serialVersionUID = 1L;

            StepBudgetExceeded() {
                super("step budget " + STEP_BUDGET + " exceeded", null, false, false);
            }
        }

        /**
         * Whether one parse with {@link ParseOptions#DEFAULT} begins at most {@link #STEP_BUDGET}
         * parser transactions. The counter is an observer: its exception aborts the parse and
         * propagates unchanged (docs/parser-observer-failures.md); the context is then discarded.
         * The observed configurations are expected to stay within a small multiple of this count:
         * memo hits only skip work, and the DETAILED_ON_FAILURE retry repeats this detailed parse once.
         */
        boolean withinBudget(String input, Stats stats) {
            long[] steps = {0};
            try (var context = ParseContext.withOptions(StringSource.createRootSource(input), ParseOptions.DEFAULT)) {
                context.addMemoizationTransparentTransactionListener(Name.of("pbt-step-budget"), new TransactionListener() {
                    @Override public void setLevel(OutputLevel level) {}
                    @Override public void onOpen(ParseContext c) {}
                    @Override public void onBegin(ParseContext c, Parser parser) {
                        if (++steps[0] > STEP_BUDGET) throw new StepBudgetExceeded();
                    }
                    @Override public void onClose(ParseContext c) {}
                });
                root.parse(context);
            } catch (StepBudgetExceeded exceeded) {
                return false;
            }
            this.steps.put(input, steps[0]);
            if (stats != null && steps[0] > stats.maxSteps) {
                stats.maxSteps = steps[0];
                stats.maxStepsInput = caseId + " input=" + input;
            }
            return true;
        }

        /** Full-input acceptance with default options (used only to pick reserve inputs). */
        boolean accepts(String input) throws Exception {
            return ((Optional<?>) mapper.getMethod("diagnose", String.class, ParseOptions.class)
                    .invoke(null, input, ParseOptions.DEFAULT)).isEmpty();
        }

        JsonObject observe(String input, String memo, String diagnostics, boolean reset) throws Exception {
            var options = ParseOptions.withMemoization(Memoization.valueOf(memo))
                    .withDiagnostics(ParseOptions.Diagnostics.valueOf(diagnostics));
            var violations = new JsonArray();
            JsonObject first = contextParse(input, options, reset, violations, true);
            JsonObject second = contextParse(input, options, reset, violations, false);
            for (String key : List.of("ok", "pos", "matched", "cst", "owned"))
                if (!first.get(key).equals(second.get(key))) violations.add("nondeterministic:" + key);
            var out = new JsonObject();
            for (String key : List.of("ok", "pos", "matched", "cst", "owned")) out.add(key, first.get(key));
            out.add("stack", first.get("stack"));
            out.add("far", first.get("far"));
            if (!first.get("stack").equals(second.get("stack"))) violations.add("nondeterministic:stack");
            var diagnostic = (Optional<?>) mapper.getMethod("diagnose", String.class, ParseOptions.class).invoke(null, input, options);
            if (diagnostic.isPresent()) {
                Object d = diagnostic.get();
                var diag = new JsonObject();
                diag.addProperty("kind", (String) d.getClass().getMethod("kind").invoke(d));
                diag.addProperty("offset", (Integer) d.getClass().getMethod("offset").invoke(d));
                out.add("diag", diag);
                var hint = new JsonObject();
                hint.addProperty("far", (Integer) d.getClass().getMethod("farthestOffset").invoke(d));
                hint.add("expected", sorted((List<?>) d.getClass().getMethod("farthestExpected").invoke(d)));
                out.add("hint", hint);
                out.add("ast", JsonNull.INSTANCE);
            } else {
                out.add("diag", JsonNull.INSTANCE);
                out.add("hint", JsonNull.INSTANCE);
                if (!first.get("ok").getAsBoolean() || first.get("pos").getAsInt() != input.codePointCount(0, input.length())) {
                    violations.add("diagnose-accepts-unconsumed-input");
                    out.add("ast", JsonNull.INSTANCE);
                } else out.add("ast", ast(input, options, reset));
            }
            out.add("violations", violations);
            out.add("hits", first.get("hits"));
            if (mapError != null) out.addProperty("mapError", mapError);
            mapError = null;
            return out;
        }

        private JsonElement ast(String input, ParseOptions options, boolean reset) {
            try (var context = ParseContext.withOptions(StringSource.createRootSource(input), options)) {
                context.getCurrent().setResetMatchedWithConsumed(reset);
                var parsed = root.parse(context);
                Token token = context.getCurrent().getTokens().stream().filter(t -> t.parser == root).findFirst().orElse(parsed.getRootToken(false));
                Object mapped = mapper.getMethod("mapParsedTokenWithSourceMap", Token.class).invoke(null, token);
                return canonical(mapped.getClass().getMethod("ast").invoke(mapped), mapped);
            } catch (Exception | AssertionError error) {
                Throwable cause = error;
                while (cause instanceof java.lang.reflect.InvocationTargetException && cause.getCause() != null) cause = cause.getCause();
                mapError = String.valueOf(cause);
                return new JsonPrimitive("map-error");
            }
        }

        private JsonObject contextParse(String input, ParseOptions options, boolean reset, JsonArray violations, boolean checks) {
            var out = new JsonObject();
            int length = input.codePointCount(0, input.length());
            try (var context = ParseContext.withOptions(StringSource.createRootSource(input), options)) {
                context.getCurrent().setResetMatchedWithConsumed(reset);
                int[] user = {7};
                context.registerTransactionalState(() -> {
                    int saved = user[0];
                    return () -> user[0] = saved;
                });
                var parsed = root.parse(context);
                boolean ok = parsed.isSucceeded();
                int pos = context.getConsumedPosition().value(), matched = context.getMatchedPosition().value();
                out.addProperty("stack", context.getRuleStack().map(st -> st.offset() + "|" + st.omitted() + "|"
                        + String.join(">", st.frames().stream().map(f -> f.rule() + "@" + f.start()).toList())).orElse("-"));
                out.addProperty("far", context.getParseFailureDiagnostics().getFarthestOffset());
                out.addProperty("ok", ok);
                out.addProperty("pos", pos);
                out.addProperty("matched", matched);
                var owned = new JsonObject();
                for (String name : this.owned)
                    owned.add(name, context.captured(name).map(v -> (JsonElement) new JsonPrimitive(v.text())).orElse(JsonNull.INSTANCE));
                out.add("owned", owned);
                var table = context.getPackratMemoTable();
                var hits = new JsonArray();
                hits.add(table == null ? 0 : table.successHits());
                hits.add(table == null ? 0 : table.failureHits());
                out.add("hits", hits);
                if (ok) {
                    Token token = context.getCurrent().getTokens().isEmpty() ? null : context.getCurrent().getTokens().get(0);
                    var cst = new StringBuilder();
                    if (token != null) {
                        project(token, cst, checks ? violations : new JsonArray(), 0, length, input);
                        String text = token.source.sourceAsString();
                        if (checks && !text.equals(prefix(input, pos))) violations.add("reconstruct:root text " + text);
                        if (checks) {
                            var leaves = new StringBuilder();
                            leaves(token, leaves);
                            if (!leaves.toString().equals(text)) violations.add("reconstruct:leaves " + leaves);
                        }
                    }
                    out.addProperty("cst", cst.toString());
                } else {
                    out.addProperty("cst", "");
                    if (checks) {
                        if (!context.getCurrent().getTokens().isEmpty()) violations.add("rollback:tokens");
                        if (pos != 0 || matched != 0) violations.add("rollback:cursor " + pos + "/" + matched);
                        for (String name : this.owned) if (context.captured(name).isPresent()) violations.add("rollback:owned " + name);
                        if (!org.unlaxer.dsl.runtime.ScopeStore.getAllDeclarations(context).isEmpty()) violations.add("rollback:scope");
                        if (root.parse(context).isSucceeded() || context.getConsumedPosition().value() != 0)
                            violations.add("rollback:reparse");
                    }
                }
                if (checks && user[0] != 7) violations.add("rollback:user-state");
            }
            return out;
        }

        private void project(Token token, StringBuilder out, JsonArray violations, int lo, int hi, String input) {
            String simple = token.parser.getClass().getSimpleName();
            String rule = simple.endsWith("Parser") ? simple.substring(0, simple.length() - 6) : simple;
            int start = token.source.offsetFromRoot().value();
            int end = start + token.source.codePointLength().value();
            boolean isRule = rules.contains(rule) && token.parser.getClass().getEnclosingClass() != null;
            if (isRule) {
                out.append(rule).append('[').append(start).append(',').append(end).append("](");
                if (start < lo || end > hi || start > end) violations.add("span:" + rule + "[" + start + "," + end + "] outside [" + lo + "," + hi + "]");
                lo = start;
                hi = end;
            }
            int previous = lo;
            for (Token child : token.getOriginalChildren()) {
                int childStart = child.source.offsetFromRoot().value();
                if (childStart < previous) violations.add("span:children overlap at " + childStart);
                previous = Math.max(previous, childStart + child.source.codePointLength().value());
                project(child, out, violations, lo, hi, input);
            }
            if (isRule) out.append(')');
        }

        private static void leaves(Token token, StringBuilder out) {
            if (token.getOriginalChildren().isEmpty()) out.append(token.source.sourceAsString());
            else for (Token child : token.getOriginalChildren()) leaves(child, out);
        }
    }

    static String prefix(String input, int codePoints) {
        return input.substring(0, input.offsetByCodePoints(0, Math.min(codePoints, input.codePointCount(0, input.length()))));
    }

    private static JsonArray sorted(List<?> values) {
        var array = new JsonArray();
        values.stream().map(String::valueOf).sorted().forEach(array::add);
        return array;
    }

    private static JsonObject canonical(Object ast, Object mapped) throws Exception {
        var result = new JsonObject();
        result.addProperty("type", ast.getClass().getSimpleName());
        int[] span = (int[]) ((Optional<?>) mapped.getClass().getMethod("sourceSpanOf", Object.class).invoke(mapped, ast)).orElseThrow();
        var position = new JsonArray();
        position.add(span[0]);
        position.add(span[1]);
        result.add("span", position);
        var fields = new JsonObject();
        for (var component : ast.getClass().getRecordComponents())
            fields.add(component.getName(), canonicalValue(component.getAccessor().invoke(ast), mapped));
        result.add("fields", fields);
        return result;
    }

    private static JsonElement canonicalValue(Object value, Object mapped) throws Exception {
        if (value == null) return JsonNull.INSTANCE;
        if (value instanceof String text) return new JsonPrimitive(text);
        if (value instanceof Number number) return new JsonPrimitive(number);
        if (value instanceof Boolean bool) return new JsonPrimitive(bool);
        if (value instanceof Optional<?> optional) return canonicalValue(optional.orElse(null), mapped);
        if (value instanceof List<?> list) {
            var result = new JsonArray();
            for (Object item : list) result.add(canonicalValue(item, mapped));
            return result;
        }
        return canonical(value, mapped);
    }

    private static GrammarDecl withoutWhitespaceNone(GrammarDecl grammar) {
        return new GrammarDecl(grammar.name(), grammar.imports(), grammar.settings().stream().filter(setting ->
                !(setting.key().equals("whitespace") && setting.value() instanceof StringSettingValue value
                        && value.value().equals("none"))).toList(), grammar.tokens(), grammar.rules());
    }

    private URLClassLoader compileJava(List<Prepared> prepared, Path output) throws Exception {
        var units = new ArrayList<JavaFileObject>();
        for (Prepared p : prepared)
            for (CodeGenerator generator : List.of(new ParserGenerator(), new ASTGenerator(), new MapperGenerator())) {
                var source = generator.generate(p.grammar());
                units.add(new SimpleJavaFileObject(URI.create("string:///" + source.packageName().replace('.', '/') + "/"
                        + source.className() + ".java"), JavaFileObject.Kind.SOURCE) {
                    @Override
                    public CharSequence getCharContent(boolean ignoreEncodingErrors) {
                        return source.source();
                    }
                });
            }
        Files.createDirectories(output);
        var compiler = org.unlaxer.dsl.Java21TestSupport.compiler();
        var diagnostics = new DiagnosticCollector<JavaFileObject>();
        try (var manager = compiler.getStandardFileManager(diagnostics, Locale.ROOT, StandardCharsets.UTF_8)) {
            boolean ok = compiler.getTask(null, manager, diagnostics, List.of("--release", "21", "-nowarn", "-classpath",
                    System.getProperty("java.class.path"), "-d", output.toString()), null, units).call();
            if (!ok) return null;
        }
        return new URLClassLoader(new URL[] {output.toUri().toURL()}, getClass().getClassLoader());
    }

    private Path compileRust(List<Prepared> prepared, Path dir, String name) throws Exception {
        var main = new StringBuilder(RUST_PROBE);
        for (Prepared p : prepared)
            main.append("#[path=\"g").append(p.index()).append("/native/mod.rs\"] mod g").append(p.index()).append(";\n")
                    .append("probe!(P").append(p.index()).append(", g").append(p.index()).append(");\n");
        main.append("fn dispatch(index: usize, input: &str, owned: &[&str], fields: &[&str]) {\n  match index {\n");
        int position = 0;
        for (Prepared p : prepared) main.append("    ").append(position++).append(" => observe::<P").append(p.index()).append(">(index, input, owned, fields),\n");
        main.append("    _ => panic!(\"unknown grammar\"),\n  }\n}\n");
        Path source = dir.resolve(name + ".rs");
        Files.writeString(source, main);
        Path binary = dir.resolve(name);
        Result result = execute(List.of("rustc", "--edition=2021", "-A", "warnings", "--crate-name", name.replace('-', '_'),
                "--extern", "unlaxer_runtime=" + runtime, source.toString(), "-o", binary.toString()), "", 600);
        return result.code() == 0 ? binary : null;
    }

