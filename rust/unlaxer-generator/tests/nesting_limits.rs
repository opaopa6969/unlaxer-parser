//! Nesting limits of the native generator, pinned at the boundaries that the Java host
//! shares (#740) or documents as a frontend difference (#741, docs/java-parser-limits.md).

fn recursive_plus(depth: usize) -> String {
    format!(
        "grammar Pbt {{ @package: pbt.corpus @root @mapping(N0, params=[x]) R0 ::= (H H) @x ;\n  H ::= 'n' R0 | 'y' {}H{}+ | 'a' ; }}\n",
        "(".repeat(depth),
        ")".repeat(depth)
    )
}

fn recursive_separator(depth: usize) -> String {
    format!(
        "grammar Pbt {{ @package: pbt.corpus @root @mapping(N0, params=[x]) R0 ::= (T T) @x ;\n  T ::= 'n' T | 'a' (',' % {}U{}) ; U ::= 'u' T ; }}\n",
        "(".repeat(depth),
        ")".repeat(depth)
    )
}

fn outcome(source: &str) -> Result<(), String> {
    unlaxer_generator::generate(source).map(|_| ())
}

#[test]
fn recursive_shape_analysis_shares_the_structural_depth() {
    for grammar in [recursive_plus, recursive_separator] {
        // Java rejected 85..122 with E-RECURSIVE-SHAPE before #740; both hosts accept them now.
        for depth in [84, 85, 86, 122] {
            assert_eq!(outcome(&grammar(depth)), Ok(()), "depth {depth}");
        }
        let error = outcome(&grammar(123)).unwrap_err();
        assert_eq!(error, "structural analysis depth exceeds 256");
    }
}

fn recursive_wrapped(depth: usize, open: &str, close: &str) -> String {
    format!(
        "grammar G {{ @root @mapping(N,params=[x]) R0 ::= (H H) @x; H ::= 'n' R0 | 'y' {}H{} | 'a'; }}\n",
        open.repeat(depth),
        close.repeat(depth)
    )
}

fn reference_chain(length: usize) -> String {
    let mut source = String::from("grammar G { @root @mapping(R, params=[x]) R0 ::= H0 @x;\n");
    for i in 0..length {
        source.push_str(&format!("H{i} ::= 'z' H{};\n", i + 1));
    }
    source + &format!("H{length} ::= 'n' R0 | 'y' H{length} | 'a'; }}\n")
}

fn chain_beside_nested_recursion(length: usize, depth: usize) -> String {
    let mut source =
        String::from("grammar G {\n@root @mapping(N, params=[x]) R0 ::= (H0 H0) @x ;\n");
    for i in 0..length {
        source.push_str(&format!("H{i} ::= 'z' H{} ;\n", i + 1));
    }
    source
        + &format!(
            "H{length} ::= 'n' H0 | 'a' ;\nD ::= 'n' R0 | 'y' {}D{}+ | 'a' ;\n}}\n",
            "(".repeat(depth),
            ")".repeat(depth)
        )
}

/// #740 review: the fixed point starts from a fresh structural depth rather than the
/// caller's, so these (accepted by the Java host before #740) are accepted on both hosts.
#[test]
fn recursive_shape_fixed_point_starts_from_a_fresh_depth() {
    for (open, close) in [
        ("[", "]"),
        ("{", "}"),
        ("CAPTURE(v, ", ")"),
        ("CAPTURE_SCOPE(", ")"),
    ] {
        assert_eq!(
            outcome(&recursive_wrapped(62, open, close)),
            Ok(()),
            "{open}"
        );
    }
    assert_eq!(outcome(&reference_chain(82)), Ok(()));
    // The deepest analysis (256 levels before the first revisit, then 256 in the fixed point)
    // also fits the default 2 MiB test thread stack in a debug build.
    assert_eq!(outcome(&chain_beside_nested_recursion(82, 122)), Ok(()));
    assert_eq!(
        outcome(&chain_beside_nested_recursion(83, 122)).unwrap_err(),
        "structural analysis depth exceeds 256"
    );
}

#[test]
fn frontend_nesting_limit_precedes_lowering() {
    // The rule body of H plus 127 groups is the 128th body level of the native frontend.
    assert_eq!(
        outcome(&recursive_plus(127)).unwrap_err(),
        "structural analysis depth exceeds 256"
    );
    let error = outcome(&recursive_plus(128)).unwrap_err();
    assert!(error.ends_with("UBNF nesting limit exceeded"), "{error}");
    // The separator operand sits one body level deeper.
    let error = outcome(&recursive_separator(127)).unwrap_err();
    assert!(error.ends_with("UBNF nesting limit exceeded"), "{error}");
}

// Same source as NestingLimitGrammars.numericBesideAnalysisWork; the Java conformance
// test also passes that exact source to the native CLI and compares all generated bytes.
fn numeric_beside_analysis_work(fillers: usize) -> String {
    beside_analysis_work(
        " @root @mapping(R,params=[n,x]) R0 ::= NUM @n T @x;",
        fillers,
    )
}

// Same source as NestingLimitGrammars.typeofBesideAnalysisWork (#758).
fn typeof_beside_analysis_work(fillers: usize) -> String {
    beside_analysis_work(
        " @root @mapping(R,params=[n,m,x]) R0 ::= NUM @n '=' @typeof(n) NUM @m \
         ',' @typeof(n) NUM @k T @x;",
        fillers,
    )
}

fn beside_analysis_work(root: &str, fillers: usize) -> String {
    let mut source = format!(
        "grammar G {{ token NUM = org.unlaxer.parser.elementary.NumberParser\n{root} \
         T ::= 'n' T | 'a' M; @mapping(M) M ::= 'm';\n"
    );
    for i in 0..80 {
        let next = if i == 79 {
            "M".into()
        } else {
            format!("C{}", i + 1)
        };
        source.push_str(&format!("C{i} ::= {next};\n"));
    }
    for i in 0..fillers {
        source.push_str(&format!("F{i} ::= {};\n", "'a' ".repeat(20)));
    }
    source + "}\n"
}

#[test]
fn numeric_refinement_does_not_need_the_ast_shape_fixed_point() {
    for (grammar, field) in [
        (
            numeric_beside_analysis_work as fn(usize) -> String,
            "r#n: i32",
        ),
        (typeof_beside_analysis_work, "r#m: i32"),
    ] {
        for fillers in [0, 500, 550, 560, 575] {
            let files = unlaxer_generator::generate(&grammar(fillers))
                .unwrap_or_else(|error| panic!("fillers {fillers}: {error}"));
            assert_eq!(files.len(), 5);
            let ast = &files
                .iter()
                .find(|file| file.relative_path == "ast.rs")
                .unwrap()
                .content;
            assert!(ast.contains(field), "fillers {fillers}: {ast}");
        }
        for fillers in [580, 600, 700] {
            assert_eq!(
                outcome(&grammar(fillers)).unwrap_err(),
                "E-RECURSIVE-SHAPE: analysis work exceeds 1000000"
            );
        }
    }
}

// Same mapped recursion and helper as RustNativeGeneratorTest.recursiveNestedHelper.
fn helper_beside_mapped_recursion(depth: usize, open: &str, close: &str) -> String {
    format!(
        "grammar Pbt {{ @package: pbt.corpus @root @mapping(N0, params=[x]) \
         R0 ::= (M M) @x T H; T ::= 'n' T M | 'a'; H ::= {}'a' M{}; \
         @mapping(NM) M ::= 'm'; }}",
        open.repeat(depth),
        close.repeat(depth)
    )
}

#[test]
fn generation_fits_two_megabyte_stack_through_frontend_limit() {
    // Pin the default Rust thread stack even when RUST_MIN_STACK is set by the host.
    std::thread::Builder::new()
        .stack_size(2 * 1024 * 1024)
        .spawn(|| {
            for (open, close, preferred_limit) in [
                ("[", "]", 127),
                ("(", ")?", 63),
                ("(", ")", 127),
                ("(", ")+", 85),
                ("(", ")*", 63),
                ("{", "}", 127),
            ] {
                for depth in [0, 62, 63, 64, 84, 85, 86, 93, 94, 95, 126, 127] {
                    if preferred_limit == 63 && depth > 84 {
                        assert_eq!(
                            outcome(&helper_beside_mapped_recursion(depth, open, close))
                                .unwrap_err(),
                            "structural analysis depth exceeds 256",
                            "{close} {depth}"
                        );
                        continue;
                    }
                    let files = unlaxer_generator::generate(&helper_beside_mapped_recursion(
                        depth, open, close,
                    ))
                    .unwrap_or_else(|error| panic!("{open} {depth}: {error}"));
                    assert_eq!(files.len(), 5);
                    let parser = &files
                        .iter()
                        .find(|f| f.relative_path == "parser.rs")
                        .unwrap()
                        .content;
                    assert_eq!(
                        parser.contains("Some(__preferred_cst::grammar())"),
                        depth <= preferred_limit,
                        "{open} {depth}"
                    );
                }
            }
        })
        .unwrap()
        .join()
        .unwrap();
}

#[test]
fn excessive_nesting_reports_limits_on_two_megabyte_stack() {
    std::thread::Builder::new()
        .stack_size(2 * 1024 * 1024)
        .spawn(|| {
            for (open, close) in [
                ("[", "]"),
                ("(", ")?"),
                ("(", ")"),
                ("(", ")+"),
                ("(", ")*"),
                ("{", "}"),
            ] {
                let error = outcome(&helper_beside_mapped_recursion(128, open, close)).unwrap_err();
                assert!(
                    error.ends_with("UBNF nesting limit exceeded"),
                    "{open}: {error}"
                );
            }
            assert_eq!(
                outcome(&recursive_plus(123)).unwrap_err(),
                "structural analysis depth exceeds 256"
            );
        })
        .unwrap()
        .join()
        .unwrap();
}
