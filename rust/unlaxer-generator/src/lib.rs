/// Additional LSP module for an explicitly requested stdio server.
pub fn generate_file_with_lsp(
    path: &std::path::Path,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    generate_file_with_protocols(path, true, false)
}
/// Additional strict typed AST DAP module.
pub fn generate_file_with_dap(
    path: &std::path::Path,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    generate_file_with_protocols(path, false, true)
}
/// Explicit protocol modules in canonical LSP/DAP order; five base files per grammar.
pub fn generate_file_with_protocols(
    path: &std::path::Path,
    lsp: bool,
    dap: bool,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    generate_file_with_errors(path, lsp, dap).map_err(|error| error.to_string())
}

/// File generation preserving I/O versus grammar failures for native CLI consumers.
/// The existing String-returning entry points remain available.
pub fn generate_file_with_errors(
    path: &std::path::Path,
    lsp: bool,
    dap: bool,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, input::FileError> {
    let file = modules::load_with_errors(path)?;
    generate_ast_with_protocols(&file, lsp, dap).map_err(Into::into)
}
