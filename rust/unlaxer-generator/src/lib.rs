/// Parse and validate the complete grammar before producing any artifacts.
pub fn generate(source: &str) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    let file = unlaxer_ubnf::parse(source).map_err(|error| error.to_string())?;
    generate_ast(&file)
}

pub fn generate_file(
    path: &std::path::Path,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    generate_ast(&modules::load(path)?)
}

fn generate_ast(
    file: &unlaxer_ubnf::UbnfFile,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    generate_ast_with_protocols(file, false, false)
}

fn generate_ast_with_protocols(
    file: &unlaxer_ubnf::UbnfFile,
    lsp: bool,
    dap: bool,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    grammar_files::validate(file)?;
    let multiple = file.grammars.len() > 1;
    let mut files = Vec::new();
    let mut index = String::from("// Generated by unlaxer RustBackend. Regenerate; do not edit.\n");
    for grammar in &file.grammars {
        let mut generated = (|| -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
            let mut generated = generate_grammar(grammar)?;
            if lsp || dap {
                let ir = lowering::lower(grammar)?;
                if lsp {
                    generated[0].content.push_str("pub mod lsp;\n");
                    generated.push(unlaxer_codegen::lsp::generate(&ir, &grammar.name));
                }
                if dap {
                    generated[0].content.push_str("pub mod dap;\n");
                    generated.push(unlaxer_codegen::dap::generate(&ir));
                }
            }
            Ok(generated)
        })()
        .map_err(|error| {
            if multiple {
                format!(
                    "grammar {} [{},{}): {error}",
                    grammar.name, grammar.span.codepoint_start, grammar.span.codepoint_end
                )
            } else {
                error
            }
        })?;
        if multiple {
            let module = grammar_files::module_name(grammar);
            index.push_str(&format!("pub mod {module};\n"));
            for artifact in &mut generated {
                artifact.relative_path = format!("{module}/{}", artifact.relative_path);
            }
        }
        files.extend(generated);
    }
    if multiple {
        // Publish the index only after every child module has been written.
        files.push(unlaxer_codegen::GeneratedFile {
            relative_path: "mod.rs".into(),
            content: index,
        });
    }
    Ok(files)
}
pub(crate) fn generate_grammar(
    grammar: &unlaxer_ubnf::GrammarDecl,
) -> Result<Vec<unlaxer_codegen::GeneratedFile>, String> {
    let ir = lowering::lower(grammar)?;
    let mut files = unlaxer_codegen::generate(&ir).map_err(|error| error.to_string())?;
    let evaluator = files
        .iter_mut()
        .find(|f| f.relative_path == "evaluator.rs")
        .unwrap();
    evaluator.content = evaluation::apply(grammar, &ir, std::mem::take(&mut evaluator.content))?;
    files
        .iter_mut()
        .find(|f| f.relative_path == "ast.rs")
        .unwrap()
        .content
        .push_str(&common_fields::emit(grammar, &ir)?);
    let parser_source = &files
        .iter()
        .find(|f| f.relative_path == "parser.rs")
        .unwrap()
        .content;
    let ast_source = &files
        .iter()
        .find(|f| f.relative_path == "ast.rs")
        .unwrap()
        .content;
    let (parser, mapper) = preferred::emit(grammar, &ir, parser_source, ast_source);
    files
        .iter_mut()
        .find(|f| f.relative_path == "parser.rs")
        .unwrap()
        .content
        .push_str(&parser);
    files
        .iter_mut()
        .find(|f| f.relative_path == "mapper.rs")
        .unwrap()
        .content
        .push_str(&mapper);
    if token_stream::enabled(grammar) {
        let api = unlaxer_codegen::lexing_api_with_profile(
            &token_stream::terminals(grammar)?,
            ir.root,
            ir.java_whitespace,
            token_stream::named_trivia(grammar)?.as_ref(),
            lexical_contexts::enabled(grammar),
        );
        files
            .iter_mut()
            .find(|f| f.relative_path == "parser.rs")
            .unwrap()
            .content
            .push_str(&api);
    }
    files
        .iter_mut()
        .find(|f| f.relative_path == "parser.rs")
        .unwrap()
        .content
        .push_str(&embedded::api(grammar, &ir)?);
    Ok(files)
}

